pub struct Crab {
    pub x: i32,
    pub y: i32,
    frame: bool,
}

impl Crab {
    pub fn new(x: i32, y: i32) -> Self {
        Self { x, y, frame: false }
    }

    // MS : 100 ms
    pub fn step_us(&self) -> u64 {
        100_000
    }

    pub fn update(&mut self) {
        self.frame = !self.frame;
    }

    pub fn draw<PINS: Outputs>(&self, display: &mut Hub75<PINS>) {
        let sprite = if self.frame { &CRAB2 } else { &CRAB1 };

        draw_sprite(display, sprite, GREEN);
    }
}

// ============================================================
// ANIMATION TRAIT
// ============================================================

impl<PINS: Outputs> crate::animation::Animation<PINS> for Crab {
    fn tick(&mut self, display: &mut Hub75<PINS>) {
        self.update();
        display.clear();
        self.draw(display);
    }
}
